def _norm_token(s: str) -> str:
    s = upper(strip_accents(norm_spaces(s)))
    s = re.sub(r'[^A-Z0-9\.\-\/ ]', '', s)
    s = norm_spaces(s)
    return s

def extract_fallback_domicilio_tokens(text):
    t = _norm_token(text)
    toks = []

    def add(x):
        x = _norm_token(x)
        if not x:
            return
        if len(x) > 28:
            x = x[:28].rstrip('.-/ ')
        if x and x not in toks:
            toks.append(x)

    for m in re.finditer(r'\bACUMULACI(?:ON|ON)\s+DE\s+PARCELA\s+([A-Z0-9\-]+)\b', t, re.I):
        add(f"ACUM.PARC.{m.group(1)}")

    for m in re.finditer(r'\bPARCELA\s+([A-Z0-9\-]+)\b', t, re.I):
        add(f"PARC.{m.group(1)}")

    m = re.search(r'\bAREA\s+REMANENTE\s+DE\s+LA\s+PARCELA\s+([A-Z0-9]+)\s+Y\s+([A-Z0-9]+)\b', t, re.I)
    if m:
        add(f"REM.PARC.{m.group(1)}-{m.group(2)}")

    for m in re.finditer(r'\bSUB\s*LOTE\s*(?:' + NUMTOK + r'\s*)?([A-Z0-9\-]+)\b', t, re.I):
        add(f"SUBLT.{m.group(1)}")

    for m in re.finditer(r'\b(?:LT|LOTE)\b\.?\s*(?:' + NUMTOK + r'\s*)?([A-Z0-9\-]+)\b', t, re.I):
        add(f"LT {m.group(1)}")

    for m in re.finditer(r'\b(?:MZ|MANZANA)\b\.?\s*([A-Z0-9\-]+)\b', t, re.I):
        add(f"MZ {m.group(1)}")

    m = re.search(r'\bFUNDO\s+([A-Z0-9 ]{3,50})', t, re.I)
    if m:
        nm = norm_spaces(m.group(1))
        nm = re.split(r'\b(,|;|/| - |\bDISTRITO\b|\bPROVINCIA\b|\bDEPARTAMENTO\b)\b', nm, maxsplit=1)[0].strip()
        if nm:
            add(f"FUNDO {nm[:22]}")

    return toks

def build_fallback_domicilio(text):
    toks = extract_fallback_domicilio_tokens(text)
    if not toks:
        return "SN"
    base = "SN"
    for tok in toks:
        cand = base + "/" + tok
        if len(cand) <= DOMICILIO_MAX:
            base = cand
        else:
            break
    return base

