def strip_accents(s):
    if not isinstance(s, str):
        return ""
    return ''.join(c for c in unicodedata.normalize('NFD', s)
                   if unicodedata.category(c) != 'Mn')

def norm_spaces(s):
    s = s if isinstance(s, str) else ""
    return re.sub(r'\s+', ' ', s).strip()

def upper(s): return (s or "").upper()
def limit(s, n): return (s or "")[:n]

def default_sn(s):
    s = (s or "").strip()
    return s if s else "SN"

def uniq_preserve(seq):
    out, seen = [], set()
    for x in seq:
        if x not in seen:
            out.append(x); seen.add(x)
    return out

def only_numbers_like(s):
    return bool(s) and re.fullmatch(r'[0-9\.\-\s]+', s.strip()) is not None

def only_digits(s):
    return re.sub(r'[^0-9]', '', s or '')

def has_two_words(s):
    return len([w for w in s.split() if w]) >= 2

def truncate_by_components(s, max_len, sep="/"):
    """
    Trunca sin cortar componentes. Ej: "A/B/C" si no cabe C, queda "A/B".
    """
    s = s or ""
    s = norm_spaces(s).strip(sep)
    if len(s) <= max_len:
        return s
    parts = [p for p in s.split(sep) if p]
    out = ""
    for p in parts:
        cand = (out + (sep if out else "") + p)
        if len(cand) <= max_len:
            out = cand
        else:
            break
    return out

def _canon_text(s: str) -> str:
    s = upper(strip_accents(norm_spaces(s or "")))
    s = re.sub(r'[^A-Z0-9 ]', ' ', s)
    s = norm_spaces(s)
    return s

def _norm_ref_token(tok: str) -> str:
    tok = upper((tok or "").strip())
    tok = re.sub(r'\s+', '', tok)
    tok = tok.strip('-')
    return tok

def is_ref_token_valid(tok: str, allow_letter_only: bool = False) -> bool:
    """
    Acepta: 5, 4C, C4, C-4, B18, B-18, E-07, 12-A, A-12, etc.
    - allow_letter_only=True permite tokens solo letras (ej: "O" en MZ O)
    - si False, exige al menos un dígito (evita basura tipo "DE")
    """
    tok = _norm_ref_token(tok)
    if not tok:
        return False
    if not re.fullmatch(r'[A-Z0-9]+(?:-[A-Z0-9]+)?', tok):
        return False
    if allow_letter_only:
        return True
    return bool(re.search(r'\d', tok))

def base_via_segment(seg: str) -> str:
    """
    Base para dedupe:
    "BOLOGNESI" y "BOLOGNESI 472" => "BOLOGNESI"
    """
    s = upper(norm_spaces(seg or ""))
    s = re.sub(r'\s+\d{1,6}(?:[-‐–—−]\d{1,6}){0,10}\s*$', '', s).strip()
    return s

# ✅ PATCH F: dedupe por contención (evita "PASEO DE ... / DE ...")
def _canon_words(s: str) -> str:
    return _canon_text(s)

def _base_words(seg: str) -> str:
    return _canon_words(base_via_segment(seg))

def is_contained_base(a: str, b: str) -> bool:
    ba = _base_words(a)
    bb = _base_words(b)
    if not ba or not bb:
        return False
    if len(ba.split()) < 2 or len(bb.split()) < 2:
        return False
    return (ba in bb) or (bb in ba)

# Serie abreviada
def abbreviate_series_for_name(nums):
    if not nums: return ""
    parts = [nums[0]]
    for n in nums[1:]:
        parts.append(("." + n[-2:]) if len(n) >= 2 else ("." + n))
    return "".join(parts)

def abbreviate_series_first_last(nums):
    return f"{nums[0]}-{nums[-1]}"

def abbreviate_series_first_last2(nums):
    last = nums[-1]
    tail = last[-2:] if len(last) >= 2 else last
    return f"{nums[0]}-.{tail}"

def abbreviate_series_compact(nums, max_len_allowed):
    """
    Compacta sin cortar “a mitad”. Si no hay espacio suficiente, retorna SOLO el primer valor.
    """
    if not nums:
        return ""
    nums = uniq_preserve(nums)
    if len(nums) <= 1:
        return nums[0]

    if max_len_allowed is None or max_len_allowed <= 0:
        return nums[0]
    if max_len_allowed < len(nums[0]) + 2:
        return nums[0]

    s1 = abbreviate_series_for_name(nums)
    if len(s1) <= max_len_allowed and len(nums) <= 10:
        return s1

    s2 = abbreviate_series_first_last(nums)
    if len(s2) <= max_len_allowed:
        return s2

    s3 = abbreviate_series_first_last2(nums)
    if len(s3) <= max_len_allowed:
        return s3

    return nums[0]

def extract_numbers_series(segment):
    raw = segment
    raw_norm = re.sub(r'[‐-–—−‒﹘﹣－]', '-', raw)
    raw_norm = re.sub(r'\s*-\s*', '-', raw_norm)  # tolera "654- 656"
    nums = re.findall(r'\d{1,6}', raw_norm)
    return nums, raw

