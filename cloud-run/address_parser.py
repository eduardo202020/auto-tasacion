def load_ubigeo(ubigeo_path):
    global UBIGEO_DF
    ext = os.path.splitext(ubigeo_path)[1].lower()
    if ext in (".xlsx", ".xls"):
        df = pd.read_excel(ubigeo_path)
    else:
        try:
            df = pd.read_csv(ubigeo_path, encoding="utf-8")
        except UnicodeDecodeError:
            df = pd.read_csv(ubigeo_path, encoding="latin-1")
    cols = { _std(c): c for c in df.columns }
    dcol = next((cols[k] for k in cols if k in ("departamento","region","dpto","depto","dep")), None)
    pcol = next((cols[k] for k in cols if k in ("provincia","prov")), None)
    tcol = next((cols[k] for k in cols if k in ("distrito","dist")), None)
    if not (dcol and pcol and tcol):
        raise ValueError("El UBIGEO debe tener columnas Departamento/Provincia/Distrito.")
    df = df.rename(columns={dcol:"DEPARTAMENTO", pcol:"PROVINCIA", tcol:"DISTRITO"})
    for c in ["DEPARTAMENTO","PROVINCIA","DISTRITO"]:
        df[c] = df[c].astype(str).map(_std)
    UBIGEO_DF = df

def _ubigeo_lookup(distrito=None, provincia=None, departamento=None):
    if UBIGEO_DF is None or not len(UBIGEO_DF): return None
    q = UBIGEO_DF
    if distrito: q = q[q["DISTRITO"] == _std(distrito)]
    if provincia and len(q): q = q[q["PROVINCIA"] == _std(provincia)]
    if departamento and len(q): q = q[q["DEPARTAMENTO"] == _std(departamento)]
    if len(q) == 1:
        r = q.iloc[0]
        return r["DISTRITO"], r["PROVINCIA"], r["DEPARTAMENTO"]
    return None

