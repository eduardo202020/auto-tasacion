def build_via_segment(v, text, index_in_chosen, current_domicilio_len, ext_digits=None):
    name_raw = v["nombre"]
    name = clean_via_name(name_raw)

    if not name:
        after = text[v["pos"]:]
        m_fallback = re.match(r'^\s*([^,;#/\-]{1,}?)(?=' + DELIMITERS + ')', after, flags=re.I)
        if m_fallback:
            name = upper(norm_spaces(m_fallback.group(1)))
        name = clean_via_name(name)

    if v["tipo"] == "PROLONGACION":
        if re.match(r'^(avenida|av\.?)\b', name, re.I):
            name = re.sub(r'^(avenida|av\.?)\b', 'AV.', name, flags=re.I)
        name = f"PROL.{name}"

    nums, _ = numbers_near_via(text, v, is_second=(index_in_chosen == 1))

    if index_in_chosen == 0:
        nums = list(nums)
        if ext_digits:
            nums = [n for n in nums if n != ext_digits]
    else:
        nums = list(nums) if ALLOW_NUMBERS_VIA_2_3 else []

    if re.search(r'\d{2,}', name):
        name = re.sub(r'\d{2,}.*$', '', name).strip()

    seg_core = name

    # 1ª vía: agrega serie si cabe
    if index_in_chosen == 0 and nums:
        left = max(0, DOMICILIO_MAX - current_domicilio_len - len(name) - 1)
        serie_str = abbreviate_series_compact(nums, left)
        if serie_str and (len(name) + 1 + len(serie_str) <= DOMICILIO_MAX - current_domicilio_len):
            seg_core = f"{name} {serie_str}".strip()

    # 2ª/3ª: un número si cabe
    if index_in_chosen > 0 and nums:
        n = nums[0]
        if len(name) >= MIN_SECOND_SEG_LEN or has_two_words(name):
            if len(name) + 1 + len(n) <= DOMICILIO_MAX - current_domicilio_len:
                seg_core = f"{name} {n}".strip()

    if v["tipo"] == "PROLONGACION":
        seg = seg_core
    else:
        pref = ABREV_TIPO.get(v["tipo"])
        if DOMICILIO_WITH_PREFIX and pref and not re.match(rf'^{re.escape(pref)}\s+', seg_core, flags=re.I):
            seg = f"{pref} {seg_core}"
        else:
            seg = seg_core

    seg = re.sub(NUMTOK, '', seg, flags=re.I)
    seg = norm_spaces(seg)
    return seg

def build_domicilio_and_extra(vias, text, ext_val=None):
    """
    FIX 1: NO truncar a mitad, no aceptar tokens cortos tipo "CAMI",
    dedupe por base y por contención (PATCH F).
    + PATCH C/D: current_domicilio_len correcto + forzar 2da vía si cabe.
    """
    parts = []
    extra_segments = []
    proj_cond = extract_project_condominio_for_domicilio(text)
    if proj_cond:
        parts.append(proj_cond)

    chosen = choose_primary_vias(vias, text, top=3)
    ext_digits = only_digits(ext_val)

    def can_add(seg, current):
        seg = seg.strip()
        if not seg: return False
        if only_numbers_like(seg): return False
        if len(seg) < MIN_SECOND_SEG_LEN and not has_two_words(seg):
            return False
        already = current.split('/') if current else []
        if seg in already: return False
        return True

    def base_exists(seg, current_parts):
        b = base_via_segment(seg)
        for p in current_parts:
            if base_via_segment(p) == b:
                return True
            if is_contained_base(seg, p):  # ✅ PATCH F
                return True
        return False

    for idx, v in enumerate(chosen):
        seg = build_via_segment(
            v, text, idx,
            current_domicilio_len=len("/".join([p for p in parts if p])),  # ✅ PATCH C
            ext_digits=ext_digits if idx == 0 else None
        )
        if not seg or not seg.strip() or only_numbers_like(seg):
            continue

        if base_exists(seg, parts):
            continue

        current = "/".join(parts)
        cand = current + ("/" if current else "") + seg

        if len(cand) <= DOMICILIO_MAX and can_add(seg, current):
            parts.append(seg)
        else:
            name_only = clean_via_name(v["nombre"])
            if name_only and not base_exists(name_only, parts):
                cand2 = current + ("/" if current else "") + name_only
                if len(cand2) <= DOMICILIO_MAX and can_add(name_only, current):
                    parts.append(name_only)
                else:
                    extra_segments.append(seg)
            else:
                extra_segments.append(seg)

    domicilio = "/".join([p for p in parts if p and p.strip()])
    domicilio = truncate_by_components(domicilio, DOMICILIO_MAX)

    for seg in [s for s in extra_segments if s and s.strip() and not only_numbers_like(s)]:
        seg = norm_spaces(seg)
        if len(seg) < MIN_SECOND_SEG_LEN and not has_two_words(seg):
            continue
        current_parts = [p for p in domicilio.split("/") if p]
        if base_exists(seg, current_parts):
            continue
        cand = domicilio + ("/" if domicilio else "") + seg
        cand2 = truncate_by_components(cand, DOMICILIO_MAX)
        if cand2 == cand:
            domicilio = cand2

    # ✅ PATCH D: si hay 2 vías detectadas pero solo quedó 1 en DOMICILIO, intenta agregar la 2da vía
    chosen2 = choose_primary_vias(vias, text, top=3)
    curr_parts = [p for p in domicilio.split("/") if p]
    via_parts_count = len(curr_parts) - (1 if proj_cond and curr_parts and is_contained_base(curr_parts[0], proj_cond) else 0)

    if len(chosen2) >= 2 and via_parts_count < 2:
        seg2 = build_via_segment(
            chosen2[1], text, 1,
            current_domicilio_len=len(domicilio),
            ext_digits=None
        )
        seg2 = norm_spaces(seg2)
        if seg2 and not only_numbers_like(seg2) and len(seg2) >= MIN_SECOND_SEG_LEN:
            if not any(is_contained_base(seg2, p) for p in curr_parts):
                cand = domicilio + ("/" if domicilio else "") + seg2
                if len(cand) <= DOMICILIO_MAX:
                    domicilio = cand

    domicilio = domicilio.strip('/')
    domicilio = re.sub(r'/{2,}', '/', domicilio)
    return domicilio, extra_segments, proj_cond

