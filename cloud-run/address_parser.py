def numbers_near_via(text, v, is_second=False):
    window = 220
    seg = text[v["pos"]: v["pos"] + window]

    seg = CONNECTORS_RE.split(seg)[0]
    seg = ATTR_CUTOFF_RE.split(seg)[0]

    seg = re.split(r'(?:,|;|/)', seg)[0]
    seg = re.split(r'(?<!\d)\s*-\s*(?!\d)', seg)[0]

    filtered = []
    base_abs = v["pos"]

    for m in re.finditer(r'\d{1,6}', seg):
        abs_idx = base_abs + m.start()
        if "name_end" in v and abs_idx < v["name_end"]:
            continue
        if not _has_negative_context(seg, m.start(), window=20):
            filtered.append(m.group(0))

    if is_second and not filtered:
        filtered = extract_corner_numbers_for_second_via(text, v["pos"])

    return uniq_preserve(filtered), seg

