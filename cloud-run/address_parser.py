def _has_negative_context(text, start_idx, window=25):
    prev_seg = text[max(0, start_idx-window):start_idx]
    return re.search(r'\b(' + '|'.join(NEGATIVE_CONTEXT_WORDS) + r')\b', prev_seg, re.I) is not None

def extract_exterior(text, primary_vias):
    seg_start = primary_vias[0]["pos"] if primary_vias else 0
    seg = text[seg_start:]

    for m in re.finditer(
        r'(?:\b' + NUMTOK + r'\s*)?(\d{1,6}(?:\s*[-–—]\s*\d{1,6}){1,20})\b',
        seg, re.I
    ):
        if _has_negative_context(seg, m.start(), window=35):
            continue
        nums, raw = extract_numbers_series(m.group(1))
        if nums:
            first = nums[0]
            return limit(upper(first), EXT_MAX), upper(raw)

    for m2 in re.finditer(r'(?:\b' + NUMTOK + r'\s*)?(\d{1,6}(?:[A-Z]|-[0-9A-Z]+)?)\b', seg, re.I):
        if _has_negative_context(seg, m2.start(), window=35):
            continue
        val = upper(m2.group(1))
        return limit(val, EXT_MAX), val

    m3 = re.search(r'\bkm\.?\s*(\d{1,3}(?:[.,]\d{1,2}|\s*1/2)?)\b', seg, re.I)
    if m3:
        raw_km = m3.group(1)
        val_num = raw_km.replace(',', '.')
        val_num = re.sub(r'\s*1/2$', '.5', val_num)
        val = upper(f"KM {val_num}")
        return limit(val, EXT_MAX), val

    if re.search(r'\bs[/ ]?n\b|sin\s+n[uú]mero', seg, re.I):
        return "S/N", "S/N"

    # MZ como exterior (tu lógica)
    mz = re.search(r'\b(mz|manzana)\b\.?\s*([A-Z0-9\-]+)', text, re.I)
    if mz:
        tok = _norm_ref_token(mz.group(2))
        if is_ref_token_valid(tok, allow_letter_only=True):
            val = f"MZ {tok}"
            return limit(val, EXT_MAX), val

    return "", ""

