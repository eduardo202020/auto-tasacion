def _normalize_interior_val(val):
    val = upper(val or "").strip()
    mfix = re.match(r'^(\d{1,6})-[A-ZÁÉÍÓÚÜÑ]{2,}$', val, re.I)
    if mfix:
        val = mfix.group(1)
    if val in {"DE","DEL","LA","EL","LOS","LAS","Y"}:
        return ""
    if not re.search(r'\d', val) and len(val) <= 3:
        return ""
    return val

def extract_interior(text):
    numtag = r'(?:n°|nº|nro|nros|no\.?|num\.?|#)'

    patterns_numtag_first = [
        rf'\b(departamento|dep|dpto|depto)\b[^,;#\n]*?{numtag}\s*([A-Z0-9\-]+)',
        rf'\b(apartamento|apto|ap\.?|apt)\b[^,;#\n]*?{numtag}\s*([A-Z0-9\-]+)',
        rf'\b(oficina|of\.?|local|tienda|tda\.?)\b[^,;#\n]*?{numtag}\s*([A-Z0-9\-]+)',
        rf'\b(int\.?|interior)\b\.?\s*{numtag}\s*([A-Z0-9\-]+)',
        rf'\b(bloque|block|blk)\b\.?\s*{numtag}\s*([A-Z0-9\-]+)',
        rf'\b(stand|puesto|box|m[oó]dulo|modulo)\b[^,;#\n]*?{numtag}\s*([A-Z0-9\-]+)',
    ]
    for p in patterns_numtag_first:
        m = re.search(p, text, re.I)
        if m:
            val = _normalize_interior_val(m.group(2))
            return limit(val, INT_MAX) if val else ""

    patterns_fallback = [
        rf'\b(departamento|dep|dpto|depto)\b[^,;#\n]*?([A-Z0-9\-]+)',
        rf'\b(apartamento|apto|ap\.?|apt)\b[^,;#\n]*?([A-Z0-9\-]+)',
        rf'\b(oficina|of\.?|local|tienda|tda\.?)\b[^,;#\n]*?([A-Z0-9\-]+)',
        rf'\b(int\.?|interior)\b\.?\s*([A-Z0-9\-]+)',
        rf'\b(bloque|block|blk)\b\.?\s*([A-Z0-9\-]+)',
        rf'\b(stand|puesto|box|m[oó]dulo|modulo)\b[^,;#\n]*?([A-Z0-9\-]+)',
    ]
    for p in patterns_fallback:
        m = re.search(p, text, re.I)
        if m:
            val = _normalize_interior_val(m.group(2))
            return limit(val, INT_MAX) if val else ""
    return ""

