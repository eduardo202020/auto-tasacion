def abbreviate_project_name(name):
    words = [w for w in re.split(r'\s+', upper(name)) if w]
    if len(words) >= 2 and words[0] in ("DE","DEL") and words[1] not in ("LA","EL","LOS","LAS"):
        words = words[1:]
    if not words:
        return upper(name)
    if len(words) == 1:
        return (words[0][:4] + '.') if len(words[0]) > 4 else words[0]
    first = (words[0][:4] + '.') if len(words[0]) > 4 else words[0]
    second = words[1]
    return f"{first}{second}"

def extract_project_condominio_for_domicilio(text):
    t = text
    m = re.search(r'pertenece\s+a\s+([A-Za-zÁÉÍÓÚÜÑáéíóúüñ\' ]+?)\s+condominio\s+([A-Za-zÁÉÍÓÚÜÑáéíóúüñ\' ]+)', t, re.I)
    if m:
        proyecto = norm_spaces(m.group(1))
        cond = norm_spaces(m.group(2))
        proj_abbr = abbreviate_project_name(proyecto)
        return f"{proj_abbr} COND.{upper(cond)}"
    m2 = re.search(r'\bcondominio\b\s+([A-Za-zÁÉÍÓÚÜÑáéíóúüñ\' ]+)', t, re.I)
    if m2:
        cond = norm_spaces(m2.group(1))
        return f"COND.{upper(cond)}"
    return ""

