def roman_to_int(s):
    ROM = {'I':1,'V':5,'X':10,'L':50,'C':100,'D':500,'M':1000}
    s = upper(s)
    total = 0
    prev = 0
    for ch in reversed(s):
        v = ROM.get(ch,0)
        if v < prev: total -= v
        else: total += v
        prev = v
    return str(total) if total else ""

def extract_referencia(text):
    ref = []
    raw_parts = []

    piso = re.search(r'\bpiso\b\s*(?:' + NUMTOK + r'\s*)?([0-9]{1,2}|[IVXLCDM]{1,6})\b', text, re.I)
    if piso:
        val = piso.group(1)
        if re.fullmatch(r'[IVXLCDM]+', val, re.I):
            val = roman_to_int(val)
        if val:
            ref.append(f"PS{upper(val)}")
            raw_parts.append(piso.group(0))

    piso_word = re.search(
        r'\b('
        r'primer[oa]?|segund[oa]|tercer[oa]?|cuart[oa]|quint[oa]|sext[oa]|s[eé]ptim[oa]|octav[oa]|noven[oa]|'
        r'd[eé]cim[oa](?:\s+(?:primer[oa]?|segund[oa]|tercer[oa]?|cuart[oa]|quint[oa]|sext[oa]|s[eé]ptim[oa]|octav[oa]|noven[oa]))?'
        r')\b\s+(?:piso|nivel)',
        text, re.I
    )
    if piso_word:
        key = upper(strip_accents(norm_spaces(piso_word.group(1))))
        num = ORDINALS.get(key, "")
        if num:
            ref.append(f"PS{num}")
            raw_parts.append(piso_word.group(0))

    torre = re.search(r'\btorre\b[^A-Z0-9\-]*([A-Z0-9]+(?:-[A-Z0-9]+)?)', text, re.I)
    if torre:
        tok = _norm_ref_token(torre.group(1))
        if is_ref_token_valid(tok, allow_letter_only=False):
            ref.append(f"TORR.{tok}")
            raw_parts.append(torre.group(0))

    est = re.search(
        r'\b(est(?:\.|acionamiento)?|cochera)\b[^A-Z0-9\-]*?(?:' + NUMTOK + r'\s*)?([A-Z0-9]+(?:-[A-Z0-9]+)?)',
        text, re.I
    )
    if est:
        tok = _norm_ref_token(est.group(2))
        if is_ref_token_valid(tok, allow_letter_only=False):
            ref.append(f"E.{tok}")
            raw_parts.append(est.group(0))

    sot = re.search(
        r'\b(semi\s*s[oó]tano|s[oó]tano)\b[^A-Z0-9\-]*([A-Z0-9]+(?:-[A-Z0-9]+)?)',
        text, re.I
    )
