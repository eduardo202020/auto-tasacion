def clean_via_name(name):
    original = name
    name = re.sub(r'\bnum\.?\b', '', name, flags=re.I)
    name = re.sub(r'\bn[uú]mero\b', '', name, flags=re.I)
    name = re.sub(r'\b(que da a|frente a|esquina(?:\s+con)?|esq\.?)\b', '', name, flags=re.I)

    NUMTOK_SUFFIX = r'(?:' + NUMTOK + r'|n\.?(?=\s*\d))'
    name = re.sub(NUMTOK_SUFFIX + r'.*$', '', name, flags=re.I).strip()

    if re.search(r'[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]', name):
        name = re.sub(r'\s*\d{1,6}\s*(?:[-‐-–—−‒﹘﹣－]\s*\d{1,6})?\s*$', '', name).strip()
        name = re.sub(r'[-‐-–—−‒﹘﹣－]\s*$', '', name).strip()

    name = re.sub(r'^[\.\-_/]+\s*', '', name).strip()
    name = re.sub(r'\s+', ' ', name).strip()
    name = re.sub(r'\.+$', '', name).strip()

    if not name or len(name) <= 1:
        name = re.sub(NUMTOK_SUFFIX + r'.*$', '', original, flags=re.I).strip()
        name = re.sub(r'\s*\d{1,6}\s*(?:[-‐-–—−‒﹘﹣－]\s*\d{1,6})?\s*$', '', name).strip()
        name = re.sub(r'[-‐-–—−‒﹘﹣－]\s*$', '', name).strip()
        name = re.sub(r'^[\.\-_/]+\s*', '', name).strip()
        name = re.sub(r'\s+', ' ', name).strip()
        name = re.sub(r'\.+$', '', name).strip()
        if not name:
            name = original

    # ✅ FIX: si el original termina en "...ON" y el limpio quedó en "...O", recupera la N final
    o = upper(strip_accents(norm_spaces(original)))
    n = upper(strip_accents(norm_spaces(name)))
    if o.endswith("ON") and n.endswith("O") and not n.endswith("ON"):
        name = (name + "N").strip()

    return upper(name)

