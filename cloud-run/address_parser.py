def extract_ubicacion(text):
    t = norm_spaces(text)

    def _clean_nombre(x):
        x = norm_spaces(x)
        x = re.sub(r'^[“"\'(]+|[”"\')]+$', '', x).strip()
        return x

    m = re.search(
        r'\b(urb\.?|urb|urbanizaci[oó]n)\b\.?\s*(.+?)(?='
        r'(,|;|/| - |\b(distrito|provincia|departamento)\b|$))',
        t, re.I
    )
    if m:
        return "URBANIZACION", limit(upper(_clean_nombre(m.group(2))), UBIC_MAX), upper(m.group(0))

    cut = r'(,|;|/| - |\b(distrito|provincia|departamento|edificio|piso|torre|lote|manzana|mz|lt|unidad|condominio|residencial|proyecto)\b)'

    m = re.search(r'\b(condominio|residencial)\b\s+(.+?)(?=' + cut + r'|$)', t, re.I)
    if m:
        tipo = "CONDOMINIO" if re.search('condominio', m.group(1), re.I) else "RESIDENCIAL"
        return tipo, limit(upper(_clean_nombre(m.group(2))), UBIC_MAX), upper(m.group(0))

    m = re.search(r'\bproyecto\b\s+“?(.+?)”?(?=' + cut + r'|$)', t, re.I)
    if m:
        return "PROYECTO", limit(upper(_clean_nombre(m.group(1))), UBIC_MAX), upper(m.group(0))

    return "", "", ""

